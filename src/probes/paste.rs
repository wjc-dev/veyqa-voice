use std::ffi::c_void;
use std::ptr::NonNull;
use std::time::Duration;

use anyhow::{bail, Result};
use objc2::runtime::ProtocolObject;
use objc2_app_kit::{NSPasteboard, NSPasteboardItem, NSRunningApplication};
use objc2_application_services::{AXError, AXUIElement};
use objc2_core_foundation::{CFEqual, CFRetained, CFString, CFType};
use objc2_core_graphics::{
    CGEvent, CGEventFlags, CGEventSource, CGEventSourceStateID, CGEventTapLocation,
};
use objc2::rc::Retained;
use objc2_foundation::{NSArray, NSData, NSString};

const TRANSIENT_TYPE: &str = "org.nspasteboard.TransientType";
const CONCEALED_TYPE: &str = "org.nspasteboard.ConcealedType";
const AUTOGENERATED_TYPE: &str = "org.nspasteboard.AutoGeneratedType";
const RESTORED_TYPE: &str = "org.nspasteboard.RestoredType";
const TOKEN_TYPE: &str = "com.wjcdev.veyqa.private-paste-token";

struct Target {
    pid: i32,
    element: CFRetained<AXUIElement>,
}

fn cf_string(type_name: &str) -> Retained<NSString> {
    NSString::from_str(type_name)
}

fn nsdata(bytes: &[u8]) -> Retained<NSData> {
    unsafe { NSData::dataWithBytes_length(bytes.as_ptr().cast::<c_void>(), bytes.len()) }
}

fn snapshot_items(pasteboard: &NSPasteboard) -> Vec<Vec<(String, Vec<u8>)>> {
    let mut captured = Vec::new();
    let Some(items) = pasteboard.pasteboardItems() else {
        return captured;
    };
    for item in items.iter() {
        let mut representations = Vec::new();
        for type_name in item.types().iter() {
            if let Some(data) = item.dataForType(&type_name) {
                let length = data.length();
                let mut bytes = vec![0u8; length];
                if length > 0 {
                    let buffer = NonNull::new(bytes.as_mut_ptr().cast::<c_void>()).unwrap();
                    unsafe { data.getBytes_length(buffer, length) };
                }
                representations.push((type_name.to_string(), bytes));
            }
        }
        if !representations.is_empty() {
            captured.push(representations);
        }
    }
    captured
}

fn place_private_text(pasteboard: &NSPasteboard, text: &str, token: &str) -> Result<()> {
    pasteboard.clearContents();
    let item = NSPasteboardItem::new();
    let string_type = cf_string("public.utf8-plain-text");
    if !item.setString_forType(&NSString::from_str(text), &string_type) {
        bail!("无法写入文本到剪贴板");
    }
    let empty = NSData::new();
    for type_name in [TRANSIENT_TYPE, CONCEALED_TYPE, AUTOGENERATED_TYPE] {
        item.setData_forType(&empty, &cf_string(type_name));
    }
    item.setString_forType(&NSString::from_str(token), &cf_string(TOKEN_TYPE));

    let objects = NSArray::from_slice(&[ProtocolObject::from_ref(&*item)]);
    if !pasteboard.writeObjects(&objects) {
        bail!("无法写入临时剪贴板");
    }
    Ok(())
}

fn restore_pasteboard(
    pasteboard: &NSPasteboard,
    snapshot: &[Vec<(String, Vec<u8>)>],
    token: &str,
) -> Result<bool> {
    let current = pasteboard.stringForType(&cf_string(TOKEN_TYPE));
    let ours = current
        .as_deref()
        .map(|value| value.to_string())
        .as_deref()
        == Some(token);
    if !ours {
        println!("剪贴板在粘贴期间被其他应用更新，保留用户的新内容");
        return Ok(false);
    }

    pasteboard.clearContents();
    if snapshot.is_empty() {
        return Ok(true);
    }
    let mut retained = Vec::new();
    for representations in snapshot {
        let item = NSPasteboardItem::new();
        for (type_name, bytes) in representations {
            item.setData_forType(&nsdata(bytes), &cf_string(type_name));
        }
        for marker in [TRANSIENT_TYPE, RESTORED_TYPE] {
            item.setData_forType(&NSData::new(), &cf_string(marker));
        }
        retained.push(item);
    }
    let restored: Vec<_> = retained
        .iter()
        .map(|item| ProtocolObject::from_ref(&**item))
        .collect();
    let objects = NSArray::from_slice(&restored);
    if !pasteboard.writeObjects(&objects) {
        bail!("无法恢复原剪贴板");
    }
    Ok(true)
}

fn post_paste_shortcut() -> Result<()> {
    let source = CGEventSource::new(CGEventSourceStateID::CombinedSessionState)
        .ok_or_else(|| anyhow::anyhow!("无法创建 CGEventSource"))?;
    let down = CGEvent::new_keyboard_event(Some(&source), 9, true)
        .ok_or_else(|| anyhow::anyhow!("无法创建粘贴快捷键事件"))?;
    let up = CGEvent::new_keyboard_event(Some(&source), 9, false)
        .ok_or_else(|| anyhow::anyhow!("无法创建粘贴快捷键事件"))?;
    CGEvent::set_flags(Some(&down), CGEventFlags::MaskCommand);
    CGEvent::set_flags(Some(&up), CGEventFlags::MaskCommand);
    CGEvent::post(CGEventTapLocation::SessionEventTap, Some(&down));
    CGEvent::post(CGEventTapLocation::SessionEventTap, Some(&up));
    Ok(())
}

unsafe fn copy_attribute(element: &AXUIElement, name: &'static str) -> Option<CFRetained<CFType>> {
    let (value, _) = unsafe { copy_attribute_result(element, name) };
    value
}

unsafe fn copy_attribute_result(
    element: &AXUIElement,
    name: &'static str,
) -> (Option<CFRetained<CFType>>, AXError) {
    let attribute = CFString::from_static_str(name);
    let mut value: *const CFType = std::ptr::null();
    let error = unsafe {
        element.copy_attribute_value(&attribute, NonNull::from(&mut value))
    };
    if error != AXError::Success || value.is_null() {
        return (None, error);
    }
    (
        Some(unsafe { CFRetained::from_raw(NonNull::new(value as *mut CFType).unwrap()) }),
        error,
    )
}

fn frontmost_pid_from_windows() -> Option<libc::pid_t> {
    use objc2_core_foundation::{CFArray, CFDictionary, CFNumber, CFType};
    use objc2_core_graphics::{
        CGWindowListCopyWindowInfo, CGWindowListOption, kCGWindowLayer, kCGWindowOwnerPID,
    };

    let options =
        CGWindowListOption::OptionOnScreenOnly | CGWindowListOption::ExcludeDesktopElements;
    let windows: CFRetained<CFArray<CFDictionary<CFString, CFType>>> =
        unsafe { CFRetained::cast_unchecked(CGWindowListCopyWindowInfo(options, 0)?) };
    for index in 0..windows.len() {
        let window = windows.get(index)?;
        let number = |key: &CFString| -> Option<i32> {
            let value = window.get(key)?;
            let number: CFRetained<CFNumber> = unsafe { CFRetained::cast_unchecked(value) };
            number.as_i32()
        };
        if number(unsafe { kCGWindowLayer }) != Some(0) {
            continue;
        }
        if let Some(pid) = number(unsafe { kCGWindowOwnerPID }) {
            return Some(pid);
        }
    }
    None
}

fn capture_target() -> Result<Target> {
    // NSWorkspace.frontmostApplication 在无 NSApplication 运行循环的 CLI 进程里可能不刷新。
    // 优先用系统级 AX 的 AXFocusedApplication；不可用时按窗口层序取最前窗口的 pid。
    let system = unsafe { AXUIElement::new_system_wide() };
    unsafe { system.set_messaging_timeout(2.0) };
    let mut focused_application = None;
    for _ in 0..3 {
        focused_application = unsafe { copy_attribute(&system, "AXFocusedApplication") };
        if focused_application.is_some() {
            break;
        }
        std::thread::sleep(Duration::from_millis(100));
    }

    let (app_element, pid) = match focused_application {
        Some(value) => {
            let element: CFRetained<AXUIElement> = unsafe { CFRetained::cast_unchecked(value) };
            let mut pid: libc::pid_t = 0;
            let error = unsafe { element.pid(NonNull::from(&mut pid)) };
            if error != AXError::Success {
                bail!("无法读取焦点应用 pid: {error:?}");
            }
            (element, pid)
        }
        None => {
            let pid = frontmost_pid_from_windows()
                .ok_or_else(|| anyhow::anyhow!("无法确定前台应用（检查辅助功能授权）"))?;
            eprintln!("系统级 AX 焦点不可用，改用窗口层序定位前台应用");
            (unsafe { AXUIElement::new_application(pid) }, pid)
        }
    };
    unsafe { app_element.set_messaging_timeout(0.5) };

    let name = NSRunningApplication::runningApplicationWithProcessIdentifier(pid)
        .and_then(|application| application.localizedName().map(|name| name.to_string()))
        .unwrap_or_else(|| format!("pid {pid}"));

    let focused = unsafe { copy_attribute(&app_element, "AXFocusedUIElement") }
        .ok_or_else(|| anyhow::anyhow!("焦点应用 {name} 没有可访问的焦点元素（pid={pid}）"))?;
    let element: CFRetained<AXUIElement> = unsafe { CFRetained::cast_unchecked(focused) };
    unsafe { element.set_messaging_timeout(0.5) };

    println!("前台应用: {name} (pid={pid})");
    println!("{}", describe(&element));
    Ok(Target { pid, element })
}

fn describe(element: &AXUIElement) -> String {
    let role = unsafe { copy_attribute(element, "AXRole") }
        .map(|value| {
            let string: CFRetained<CFString> = unsafe { CFRetained::cast_unchecked(value) };
            string.to_string()
        })
        .unwrap_or_else(|| "unknown".to_string());

    let settable = |name: &'static str| -> bool {
        let attribute = CFString::from_static_str(name);
        let mut value: u8 = 0;
        let error = unsafe {
            element.is_attribute_settable(&attribute, NonNull::from(&mut value))
        };
        error == AXError::Success && value != 0
    };

    format!(
        "role={role}, selectedTextSettable={}, valueSettable={}",
        settable("AXSelectedText"),
        settable("AXValue")
    )
}

fn same_target(first: &Target, second: &Target) -> bool {
    if first.pid != second.pid {
        return false;
    }
    let a = CFRetained::as_ptr(&first.element).as_ptr().cast::<CFType>();
    let b = CFRetained::as_ptr(&second.element).as_ptr().cast::<CFType>();
    unsafe { CFEqual(Some(&*a), Some(&*b)) }
}

pub fn run(text: String, delay_seconds: f32, inspect_only: bool) -> Result<()> {
    let target = capture_target()?;

    if delay_seconds > 0.0 {
        println!();
        if inspect_only {
            println!("{delay_seconds:.1}s 后复查焦点；--inspect 模式不写剪贴板、不发送 ⌘V。");
        } else {
            println!(
                "{delay_seconds:.1}s 内请把焦点切到目标输入框（例如 TextEdit）；切窗口后本探针会拒绝盲粘。"
            );
        }
        std::thread::sleep(Duration::from_secs_f32(delay_seconds));

        let current = capture_target()?;
        if !same_target(&target, &current) {
            bail!("焦点已变化（原 pid={}，现在 pid={}），拒绝写入", target.pid, current.pid);
        }
        println!("焦点校验通过（CFEqual）");
    }

    if inspect_only {
        println!();
        println!("--inspect 模式：只读取 AX 元数据，不写剪贴板、不发送 ⌘V。");
        return Ok(());
    }

    let pasteboard = NSPasteboard::generalPasteboard();
    let snapshot = snapshot_items(&pasteboard);
    let token = uuid::Uuid::new_v4().to_string();
    println!(
        "剪贴板快照: {} 个 item，{} 个格式",
        snapshot.len(),
        snapshot.iter().map(|item| item.len()).sum::<usize>()
    );

    place_private_text(&pasteboard, &text, &token)?;
    std::thread::sleep(Duration::from_millis(40));
    post_paste_shortcut()?;
    std::thread::sleep(Duration::from_millis(250));

    match restore_pasteboard(&pasteboard, &snapshot, &token) {
        Ok(true) => println!("已恢复原剪贴板"),
        Ok(false) => {}
        Err(error) => println!("恢复剪贴板失败: {error}"),
    }
    println!("粘贴流程完成");
    Ok(())
}
