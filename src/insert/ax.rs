    fn pasteboard_markers_match_the_python_protocol() {
        assert_eq!(TOKEN_TYPE, "com.wjcdev.veyqa.private-paste-token");
        assert_eq!(SOURCE_TYPE, "org.nspasteboard.source");
        assert_eq!(SOURCE_BUNDLE_ID, "com.wjcdev.veyqa");
    }
