//! Production macOS accessibility + clipboard insertion runtime.
//!
//! `AXUIElement` is `!Send`, so every target lives on one dedicated worker
//! thread and callers only exchange `TargetId` handles. The safety order is
//! the one already encoded in [`Committer`](super::commit::Committer):
//! capture at key-down, re-check focus with `CFEqual`, paste through the
//! clipboard, and retain the text when anything cannot be confirmed.

