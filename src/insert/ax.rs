const AX_TIMEOUT_SECONDS: f32 = 0.5;
const REQUEST_TIMEOUT: Duration = Duration::from_secs(3);
const COMMIT_TIMEOUT: Duration = Duration::from_secs(20);
const MAX_LIVE_TARGETS: usize = 4;

pub type TargetId = u64;

#[derive(Clone)]
pub struct AxTarget {
    pub pid: i32,
    pub element: CFRetained<AXUIElement>,
    id: Option<TargetId>,
}

impl AxTarget {
    pub fn bundle_identifier(&self) -> String {
        bundle_identifier_for_pid(self.pid)
    }

    pub fn target_id(&self) -> Option<TargetId> {
        self.id
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct FrontmostApp {
    pub pid: i32,
    pub bundle_id: String,
    pub name: String,
}

pub fn frontmost_application() -> Option<FrontmostApp> {
    let application = NSWorkspace::sharedWorkspace().frontmostApplication()?;
    Some(FrontmostApp {
        pid: application.processIdentifier(),
        bundle_id: application
            .bundleIdentifier()
            .map(|value| value.to_string())
            .unwrap_or_default(),
        name: application
            .localizedName()
            .map(|value| value.to_string())
            .unwrap_or_default(),
    })
}

pub fn bundle_identifier_for_pid(pid: i32) -> String {
    let Some(application) =
        NSRunningApplication::runningApplicationWithProcessIdentifier(pid)
    else {
        return String::new();
    };
    application
        .bundleIdentifier()
        .map(|value| value.to_string())
        .unwrap_or_default()
}

fn cf_string(value: &str) -> objc2::rc::Retained<NSString> {
    NSString::from_str(value)
}

fn nsdata(bytes: &[u8]) -> objc2::rc::Retained<NSData> {
    unsafe { NSData::dataWithBytes_length(bytes.as_ptr().cast::<c_void>(), bytes.len()) }
}

fn copy_attribute(element: &AXUIElement, name: &'static str) -> Option<CFRetained<CFType>> {
    let attribute = CFString::from_static_str(name);
    let mut value: *const CFType = std::ptr::null();
    let error =
        unsafe { element.copy_attribute_value(&attribute, NonNull::from(&mut value)) };
    if error != AXError::Success || value.is_null() {
        return None;
    }
    Some(unsafe { CFRetained::from_raw(NonNull::new(value as *mut CFType).unwrap()) })
}

fn copy_string_attribute(element: &AXUIElement, name: &'static str) -> Option<String> {
    let value = copy_attribute(element, name)?;
    let string = value.downcast::<CFString>().ok()?;
    Some(string.to_string())
}

fn copy_range(element: &AXUIElement) -> Option<(usize, usize)> {
    let value = copy_attribute(element, "AXSelectedTextRange")?;
    let value = value.downcast::<AXValue>().ok()?;
    let mut range = CFRange::new(0, 0);
    let ok = unsafe { value.value(AXValueType::CFRange, NonNull::from(&mut range).cast()) };
    if !ok {
        return None;
    }
    Some((range.location.max(0) as usize, range.length.max(0) as usize))
}

/// AX ranges count UTF-16 code units; the rest of the engine counts `char`s.
fn utf16_to_char_index(text: &str, utf16_index: usize) -> usize {
    if utf16_index == 0 {
        return 0;
    }
    let mut units = 0usize;
    let mut count = 0usize;
    for character in text.chars() {
        let length = character.len_utf16();
        if units + length > utf16_index {
            break;
        }
        units += length;
        count += 1;
    }
    count
}

fn parameterized_text_is_empty(element: &AXUIElement, current: &str) -> bool {
    let units = current.encode_utf16().count();
    let mut range = CFRange::new(0, units as isize);
    let Some(parameter) =
        (unsafe { AXValue::new(AXValueType::CFRange, NonNull::from(&mut range).cast()) })
    else {
        return false;
    };
    let parameter_ref: &CFType =
        unsafe { &*CFRetained::as_ptr(&parameter).as_ptr().cast::<CFType>() };
    let attribute = CFString::from_static_str("AXStringForRange");
    let mut result: *const CFType = std::ptr::null();
    let error = unsafe {
        element.copy_parameterized_attribute_value(
            &attribute,
            parameter_ref,
            NonNull::from(&mut result),
        )
    };
    if error != AXError::Success || result.is_null() {
        return false;
    }
    let value = unsafe { CFRetained::from_raw(NonNull::new(result as *mut CFType).unwrap()) };
    value
        .downcast::<CFString>()
        .map(|string| string.to_string().is_empty())
        .unwrap_or(false)
}

fn visual_placeholder_matches(target: &AxTarget, current: &str) -> bool {
    for attribute in ["AXPlaceholderValue", "AXTitle", "AXDescription", "AXHelp"] {
        if copy_string_attribute(&target.element, attribute).is_some_and(|value| value == current)
        {
            return true;
        }
    }

    let zero_characters = copy_attribute(&target.element, "AXNumberOfCharacters")
        .and_then(|value| value.downcast::<CFNumber>().ok())
        .and_then(|number| number.as_i64().or_else(|| number.as_isize().map(|n| n as i64)))
        == Some(0);
    if zero_characters {
        return true;
    }

    if parameterized_text_is_empty(&target.element, current) {
        return true;
    }

    let bundle = target.bundle_identifier();
    let normalized = current.trim().to_lowercase();
    if bundle.starts_with("com.openai.") {
        if ["do anything", "ask anything", "message chatgpt", "随心输入"]
            .contains(&normalized.as_str())
        {
            return true;
        }
    }
    if bundle.starts_with("com.qoder.ide") {
        if (current.contains("@ 添加上下文") && current.contains("/ 使用命令"))
            || (normalized.contains("@ add context") && normalized.contains("/ use commands"))
            || [
                "追加需求或提问",
                "add requirements or ask questions",
                "ask a follow-up question",
            ]
            .contains(&normalized.as_str())
        {
            return true;
        }
    }
    false
}

fn snapshot_text(target: &AxTarget) -> Option<TextSnapshot> {
    let value = copy_string_attribute(&target.element, "AXValue")?;
    let (location, length) = copy_range(&target.element)?;
    let start = utf16_to_char_index(&value, location);
    let end = utf16_to_char_index(&value, location.saturating_add(length));

    let char_count = value.chars().count();
    if value.is_empty() || start != end || (start != 0 && start != char_count) {
        return Some(TextSnapshot {
            text: value,
            selection_start: start,
            selection_end: start + end.saturating_sub(start),
        });
    }
    if visual_placeholder_matches(target, &value) {
        return Some(TextSnapshot {
            text: String::new(),
            selection_start: 0,
            selection_end: 0,
        });
    }
    Some(TextSnapshot {
        text: value,
        selection_start: start,
        selection_end: end,
    })
}

fn same_ax_target(first: &AxTarget, second: &AxTarget) -> bool {
    if first.pid != second.pid {
        return false;
    }
    let a = CFRetained::as_ptr(&first.element).as_ptr().cast::<CFType>();
    let b = CFRetained::as_ptr(&second.element).as_ptr().cast::<CFType>();
    unsafe { CFEqual(Some(&*a), Some(&*b)) }
}

fn capture_focused_target() -> Option<AxTarget> {
    let app = frontmost_application()?;
    unsafe {
        let application = AXUIElement::new_application(app.pid);
        application.set_messaging_timeout(AX_TIMEOUT_SECONDS);
        let focused = copy_attribute(&application, "AXFocusedUIElement")?;
        let element: CFRetained<AXUIElement> = CFRetained::cast_unchecked(focused);
        element.set_messaging_timeout(AX_TIMEOUT_SECONDS);
        Some(AxTarget {
            pid: app.pid,
            element,
            id: None,
        })
    }
}

#[derive(Default)]
pub struct SystemClipboard;

impl ClipboardBackend for SystemClipboard {
    fn capture(&mut self) -> PasteboardSnapshot {
        let pasteboard = NSPasteboard::generalPasteboard();
        let mut items = Vec::new();
        let Some(pasteboard_items) = pasteboard.pasteboardItems() else {
            return PasteboardSnapshot { items };
        };
        for item in pasteboard_items.iter() {
            let mut representations = Vec::new();
            for type_name in item.types().iter() {
                if let Some(data) = item.dataForType(&type_name) {
                    let length = data.length();
                    let mut bytes = vec![0u8; length];
                    if length > 0 {
                        let buffer = NonNull::new(bytes.as_mut_ptr().cast::<c_void>()).unwrap();
                        unsafe { data.getBytes_length(buffer, length) };
                    }
                    representations.push((type_name.to_string(), bytes));
                }
            }
            if !representations.is_empty() {
                items.push(representations);
            }
        }
        PasteboardSnapshot { items }
    }

    fn place_private_text(&mut self, text: &str, token: &str) -> Result<(), String> {
        let pasteboard = NSPasteboard::generalPasteboard();
        pasteboard.clearContents();
        let item = NSPasteboardItem::new();
        if !item.setString_forType(&NSString::from_str(text), &cf_string("public.utf8-plain-text")) {
            return Err("无法写入文本到剪贴板".to_string());
        }
        let empty = NSData::new();
        for type_name in [TRANSIENT_TYPE, CONCEALED_TYPE, AUTOGENERATED_TYPE] {
            item.setData_forType(&empty, &cf_string(type_name));
        }
        item.setString_forType(&NSString::from_str(SOURCE_BUNDLE_ID), &cf_string(SOURCE_TYPE));
        item.setString_forType(&NSString::from_str(token), &cf_string(TOKEN_TYPE));

        let objects = NSArray::from_slice(&[ProtocolObject::from_ref(&*item)]);
        if !pasteboard.writeObjects(&objects) {
            return Err("无法写入临时剪贴板".to_string());
        }
        Ok(())
    }

    fn current_token(&mut self) -> Option<String> {
        NSPasteboard::generalPasteboard()
            .stringForType(&cf_string(TOKEN_TYPE))
            .map(|value| value.to_string())
    }

    fn clear(&mut self) {
        NSPasteboard::generalPasteboard().clearContents();
    }

    fn write_restored(&mut self, snapshot: &PasteboardSnapshot) -> Result<(), String> {
        let pasteboard = NSPasteboard::generalPasteboard();
        pasteboard.clearContents();
        if snapshot.is_empty() {
            return Ok(());
        }
        let mut retained = Vec::new();
        for representations in &snapshot.items {
            let item = NSPasteboardItem::new();
            for (type_name, bytes) in representations {
                item.setData_forType(&nsdata(bytes), &cf_string(type_name));
            }
            for marker in [TRANSIENT_TYPE, RESTORED_TYPE] {
                item.setData_forType(&NSData::new(), &cf_string(marker));
            }
            retained.push(item);
        }
        let restored: Vec<_> = retained
            .iter()
            .map(|item| ProtocolObject::from_ref(&**item))
            .collect();
        let objects = NSArray::from_slice(&restored);
        if !pasteboard.writeObjects(&objects) {
            return Err("无法恢复原剪贴板".to_string());
        }
        Ok(())
    }
}

#[derive(Default)]
pub struct SystemPasteTrigger;

impl PasteTrigger for SystemPasteTrigger {
    fn post_paste(&mut self) -> Result<(), String> {
        let source = CGEventSource::new(CGEventSourceStateID::CombinedSessionState)
            .ok_or_else(|| "无法创建 CGEventSource".to_string())?;
        let down = CGEvent::new_keyboard_event(Some(&source), 9, true)
            .ok_or_else(|| "无法创建粘贴快捷键事件".to_string())?;
        let up = CGEvent::new_keyboard_event(Some(&source), 9, false)
            .ok_or_else(|| "无法创建粘贴快捷键事件".to_string())?;
        CGEvent::set_flags(Some(&down), CGEventFlags::MaskCommand);
        CGEvent::set_flags(Some(&up), CGEventFlags::MaskCommand);
        CGEvent::post(CGEventTapLocation::SessionEventTap, Some(&down));
        CGEvent::post(CGEventTapLocation::SessionEventTap, Some(&up));
        Ok(())
    }
}

struct MacBackend {
    clipboard: SystemClipboard,
    trigger: SystemPasteTrigger,
    corrections: Arc<CorrectionStore>,
    recovery: Arc<RecoveryStore>,
    observer_generation: Arc<AtomicU64>,
    client: AxClient,
}

impl CommitBackend<AxTarget> for MacBackend {
    fn target_is_focused(&mut self, target: &AxTarget) -> bool {
        capture_focused_target().is_some_and(|current| same_ax_target(&current, target))
    }

    fn snapshot(&mut self, target: &AxTarget) -> Option<TextSnapshot> {
        snapshot_text(target)
    }

    fn apply_corrections(&mut self, text: &str) -> String {
        self.corrections.apply(text)
    }

    fn same_target(&mut self, first: &AxTarget, second: &AxTarget) -> bool {
        same_ax_target(first, second)
    }

    fn paste(&mut self, target: &AxTarget, text: &str) -> bool {
        if !self.target_is_focused(target) {
            return false;
        }
        let window = paste_window_for_bundle(Some(&target.bundle_identifier()));
        let mut deps = PasteDeps {
            sleeper: Box::new(|seconds| thread::sleep(Duration::from_secs_f64(seconds))),
            token: Box::new(|| uuid::Uuid::new_v4().simple().to_string()),
        };
        paste_text_preserving_clipboard(
            &mut self.clipboard,
            &mut self.trigger,
            &mut deps,
            text,
            window,
        )
        .is_ok()
    }

    fn observe_after_paste(&mut self, text: &str, target: &AxTarget) {
        let Some(id) = target.id else {
            return;
        };
        if !learning_enabled() || text.is_empty() {
            return;
        }
        let generation = self.observer_generation.fetch_add(1, Ordering::SeqCst) + 1;
        let current = self.observer_generation.clone();
        let client = self.client.clone();
        let store = self.corrections.clone();
        let inserted = text.to_string();
        let _ = thread::Builder::new()
            .name("veyqa-correction-observer".to_string())
            .spawn(move || {
                observe_insertion(client, current, generation, store, id, inserted);
            });
    }

    fn retain_recovery(&mut self, text: &str, reason: &str) -> bool {
        self.recovery.add(text, reason).is_ok()
    }
}

fn observe_insertion(
    client: AxClient,
    generation_state: Arc<AtomicU64>,
    generation: u64,
    store: Arc<CorrectionStore>,
    target: TargetId,
    inserted: String,
) {
    thread::sleep(Duration::from_secs_f64(OBSERVE_INITIAL_DELAY_SECONDS));
    let Some(baseline) = client.snapshot(target) else {
        return;
    };
    let started = Instant::now();
    let Some(mut session) = ObserveSession::new(&inserted, &baseline, 0.0) else {
        return;
    };

    let mut outcome = ObserveStep::Continue;
    loop {
        if started.elapsed().as_secs_f64() >= OBSERVE_TIMEOUT_SECONDS {
            break;
        }
        if generation_state.load(Ordering::SeqCst) != generation {
            break;
        }
        thread::sleep(Duration::from_secs_f64(OBSERVE_POLL_SECONDS));
        let snapshot = client.snapshot(target);
        outcome = session.poll(snapshot.as_ref(), started.elapsed().as_secs_f64());
        if outcome != ObserveStep::Continue {
            break;
        }
    }

    let outcome = if outcome == ObserveStep::Continue {
        session.finish()
    } else {
        outcome
    };
    if let ObserveStep::Record(pairs) = outcome {
        for (wrong, correct) in pairs {
            let _ = store.record(&wrong, &correct);
        }
    }
}

enum AxCommand {
    Capture {
        reply: Sender<Option<TargetId>>,
    },
    Commit {
        target: Option<TargetId>,
        text: String,
        reply: Sender<bool>,
    },
    BundleId {
        target: TargetId,
        reply: Sender<String>,
    },
    Snapshot {
        target: TargetId,
        reply: Sender<Option<TextSnapshot>>,
    },
    /// Only the dedicated trial editor inside the settings app may receive
    /// dictation; the identifier lives on the native NSTextView.
    TrialTarget {
        target: TargetId,
        frontmost_pid: i32,
        reply: Sender<bool>,
    },
}

struct AxWorker {
    targets: HashMap<TargetId, AxTarget>,
    next_id: TargetId,
    committer: Committer<AxTarget>,
    backend: MacBackend,
}

impl AxWorker {
    fn capture(&mut self) -> Option<TargetId> {
        let mut target = capture_focused_target()?;
        self.next_id += 1;
        let id = self.next_id;
        target.id = Some(id);
        if self.targets.len() >= MAX_LIVE_TARGETS {
            if let Some(oldest) = self.targets.keys().min().copied() {
                self.targets.remove(&oldest);
            }
        }
        self.targets.insert(id, target);
        Some(id)
    }

    fn commit(&mut self, target: Option<TargetId>, text: &str) -> bool {
        let target = target.and_then(|id| self.targets.get(&id).cloned());
        let AxWorker {
            committer,
            backend,
            ..
        } = self;
        committer.commit(backend, text, target.as_ref())
    }

    fn handle(&mut self, command: AxCommand) {
        match command {
            AxCommand::Capture { reply } => {
                let _ = reply.send(self.capture());
            }
            AxCommand::Commit {
                target,
                text,
                reply,
            } => {
                let result = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
                    self.commit(target, &text)
                }))
                .unwrap_or(false);
                let _ = reply.send(result);
            }
            AxCommand::BundleId { target, reply } => {
                let bundle = self
                    .targets
                    .get(&target)
                    .map(AxTarget::bundle_identifier)
                    .unwrap_or_default();
                let _ = reply.send(bundle);
            }
            AxCommand::Snapshot { target, reply } => {
                let snapshot = self.targets.get(&target).and_then(snapshot_text);
                let _ = reply.send(snapshot);
            }
            AxCommand::TrialTarget {
                target,
                frontmost_pid,
                reply,
            } => {
                let is_trial = self
                    .targets
                    .get(&target)
                    .is_some_and(|item| item.pid == frontmost_pid)
                    && capture_focused_target()
                        .zip(self.targets.get(&target))
                        .is_some_and(|(focused, item)| same_ax_target(&focused, item))
                    && self
                        .targets
                        .get(&target)
                        .and_then(|item| copy_string_attribute(&item.element, "AXIdentifier"))
                        .is_some_and(|identifier| identifier == "veyqa.setup.trial");
                let _ = reply.send(is_trial);
            }
        }
    }
}

#[derive(Clone)]
pub struct AxClient {
    sender: Sender<AxCommand>,
}

impl AxClient {
    pub fn spawn(recovery: Arc<RecoveryStore>) -> Self {
        Self::spawn_with_corrections(recovery, Arc::new(CorrectionStore::new(None)))
    }

    pub fn spawn_with_corrections(
        recovery: Arc<RecoveryStore>,
        corrections: Arc<CorrectionStore>,
    ) -> Self {
        let (sender, receiver) = bounded(64);
        let client = Self {
            sender: sender.clone(),
        };
        let backend = MacBackend {
            clipboard: SystemClipboard,
            trigger: SystemPasteTrigger,
            corrections,
            recovery,
            observer_generation: Arc::new(AtomicU64::new(0)),
            client: client.clone(),
        };
        thread::Builder::new()
            .name("veyqa-ax".to_string())
            .spawn(move || run_worker(receiver, backend))
            .expect("无法启动 AX 线程");
        client
    }

    pub fn capture(&self) -> Option<TargetId> {
        let (reply, receiver) = bounded(1);
        self.send(AxCommand::Capture { reply })?;
        receiver.recv_timeout(REQUEST_TIMEOUT).ok().flatten()
    }

    pub fn commit(&self, target: Option<TargetId>, text: &str) -> bool {
        let (reply, receiver) = bounded(1);
        let command = AxCommand::Commit {
            target,
            text: text.to_string(),
            reply,
        };
        if self.send(command).is_none() {
            return false;
        }
        receiver.recv_timeout(COMMIT_TIMEOUT).unwrap_or(false)
    }

    pub fn bundle_identifier(&self, target: TargetId) -> String {
        let (reply, receiver) = bounded(1);
        if self.send(AxCommand::BundleId { target, reply }).is_none() {
            return String::new();
        }
        receiver.recv_timeout(REQUEST_TIMEOUT).unwrap_or_default()
    }

    pub fn snapshot(&self, target: TargetId) -> Option<TextSnapshot> {
        let (reply, receiver) = bounded(1);
        self.send(AxCommand::Snapshot { target, reply })?;
        receiver.recv_timeout(REQUEST_TIMEOUT).ok().flatten()
    }

    pub fn is_setup_trial_target(&self, target: TargetId, frontmost_pid: i32) -> bool {
        let (reply, receiver) = bounded(1);
        let command = AxCommand::TrialTarget {
            target,
            frontmost_pid,
            reply,
        };
        if self.send(command).is_none() {
            return false;
        }
        receiver.recv_timeout(REQUEST_TIMEOUT).unwrap_or(false)
    }

    fn send(&self, command: AxCommand) -> Option<()> {
        self.sender.send_timeout(command, REQUEST_TIMEOUT).ok()
    }
}

fn run_worker(receiver: Receiver<AxCommand>, backend: MacBackend) {
    let mut worker = AxWorker {
        targets: HashMap::new(),
        next_id: 0,
        committer: Committer::new(),
        backend,
    };
    while let Ok(command) = receiver.recv() {
        worker.handle(command);
    }
}

