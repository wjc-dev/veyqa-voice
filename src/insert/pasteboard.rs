//! Compatibility-first paste with lossless clipboard restoration.
//!
//! Mirrors `src/clipboard_paste.py`. The AppKit pasteboard is behind
//! `ClipboardBackend`, so snapshot ordering, token gating, and settle windows
//! are testable without touching the user's clipboard.

pub const TRANSIENT_TYPE: &str = "org.nspasteboard.TransientType";
pub const CONCEALED_TYPE: &str = "org.nspasteboard.ConcealedType";
pub const AUTOGENERATED_TYPE: &str = "org.nspasteboard.AutoGeneratedType";
pub const RESTORED_TYPE: &str = "org.nspasteboard.RestoredType";
pub const SOURCE_TYPE: &str = "org.nspasteboard.source";
pub const TOKEN_TYPE: &str = "com.wjcdev.veyqa.private-paste-token";
pub const SOURCE_BUNDLE_ID: &str = "com.wjcdev.veyqa";

pub const DEFAULT_SETTLE_SECONDS: f64 = 0.25;
pub const WECHAT_SETTLE_SECONDS: f64 = 0.85;
pub const BEFORE_PASTE_SECONDS: f64 = 0.04;
pub const MIN_SETTLE_SECONDS: f64 = 0.05;

/// Every pasteboard item and representation, retained only in memory.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct PasteboardSnapshot {
    pub items: Vec<Vec<(String, Vec<u8>)>>,
}

impl PasteboardSnapshot {
    pub fn is_empty(&self) -> bool {
        self.items.is_empty()
    }

    pub fn representation_count(&self) -> usize {
        self.items.iter().map(Vec::len).sum()
    }
}

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct PasteWindow {
    pub before_paste_seconds: f64,
    pub settle_seconds: f64,
}

impl Default for PasteWindow {
    fn default() -> Self {
        Self {
            before_paste_seconds: BEFORE_PASTE_SECONDS,
            settle_seconds: DEFAULT_SETTLE_SECONDS,
        }
    }
}

/// WeChat's macOS composer consumes the pasteboard asynchronously, so it keeps
/// a longer private-paste window. Other apps keep the fast path.
pub fn paste_window_for_bundle(bundle_id: Option<&str>) -> PasteWindow {
    let bundle = bundle_id.unwrap_or("").to_lowercase();
    let settle_seconds = if bundle.contains("wechat") || bundle.contains("xwechat") {
        WECHAT_SETTLE_SECONDS
    } else {
        DEFAULT_SETTLE_SECONDS
    };
    PasteWindow {
        before_paste_seconds: BEFORE_PASTE_SECONDS,
        settle_seconds,
    }
}

/// If the user copies something during the paste window, their new clipboard
/// wins and must never be overwritten.
pub fn should_restore(current_token: Option<&str>, our_token: &str) -> bool {
    current_token == Some(our_token)
}

pub trait ClipboardBackend {
    fn capture(&mut self) -> PasteboardSnapshot;
    fn place_private_text(&mut self, text: &str, token: &str) -> Result<(), String>;
    fn current_token(&mut self) -> Option<String>;
    fn clear(&mut self);
    fn write_restored(&mut self, snapshot: &PasteboardSnapshot) -> Result<(), String>;
}

pub trait PasteTrigger {
    fn post_paste(&mut self) -> Result<(), String>;
}

/// Sleeps are injected so the ordering contract tests stay instant.
pub type Sleeper<'a> = Box<dyn FnMut(f64) + 'a>;
pub type TokenFactory<'a> = Box<dyn FnMut() -> String + 'a>;

pub struct PasteDeps<'a> {
    pub sleeper: Sleeper<'a>,
    pub token: TokenFactory<'a>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PasteOutcome {
    Pasted,
    EmptyText,
    Restored,
    /// The user (or another app) replaced the clipboard mid-paste.
    RestoreSkipped,
}

/// Paste text, then restore every available original representation.
///
/// Returns `Err` only when the temporary item could not be placed; restoration
/// still runs and its failures are swallowed exactly like the Python finally.
pub fn paste_text_preserving_clipboard<B, T>(
    backend: &mut B,
    trigger: &mut T,
    deps: &mut PasteDeps<'_>,
    text: &str,
    window: PasteWindow,
) -> Result<PasteOutcome, String>
where
    B: ClipboardBackend,
    T: PasteTrigger,
{
    if text.is_empty() {
        return Ok(PasteOutcome::EmptyText);
    }

    let snapshot = backend.capture();
    let token = (deps.token)();
    let placed = backend.place_private_text(text, &token);
    if let Err(error) = placed {
        restore(backend, &snapshot, &token);
        return Err(error);
    }

    (deps.sleeper)(window.before_paste_seconds.max(0.0));
    let posted = trigger.post_paste();
    (deps.sleeper)(window.settle_seconds.max(MIN_SETTLE_SECONDS));
    let restored = restore(backend, &snapshot, &token);
    posted?;
    Ok(if restored {
        PasteOutcome::Restored
    } else {
        PasteOutcome::RestoreSkipped
    })
}

fn restore<B: ClipboardBackend>(
    backend: &mut B,
    snapshot: &PasteboardSnapshot,
    token: &str,
) -> bool {
    if !should_restore(backend.current_token().as_deref(), token) {
        return false;
    }
    backend.clear();
    if snapshot.is_empty() {
        return true;
    }
    backend.write_restored(snapshot).is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[derive(Default)]
    struct FakeClipboard {
        snapshot: PasteboardSnapshot,
        items: Vec<Vec<(String, Vec<u8>)>>,
        token: Option<String>,
        actions: Vec<String>,
        restore_error: bool,
    }

    impl ClipboardBackend for FakeClipboard {
        fn capture(&mut self) -> PasteboardSnapshot {
            self.actions.push("capture".to_string());
            self.snapshot.clone()
        }

        fn place_private_text(&mut self, text: &str, token: &str) -> Result<(), String> {
            self.actions.push(format!("place:{text}:{token}"));
            self.items = vec![vec![("public.utf8-plain-text".to_string(), text.as_bytes().to_vec())]];
            self.token = Some(token.to_string());
            Ok(())
        }

        fn current_token(&mut self) -> Option<String> {
            self.actions.push("token".to_string());
            self.token.clone()
        }

        fn clear(&mut self) {
            self.actions.push("clear".to_string());
            self.items.clear();
        }

        fn write_restored(&mut self, snapshot: &PasteboardSnapshot) -> Result<(), String> {
            self.actions.push("write_restored".to_string());
            if self.restore_error {
                return Err("无法恢复原剪贴板".to_string());
            }
            self.items = snapshot.items.clone();
            Ok(())
        }
    }

    #[derive(Default)]
    struct FakeTrigger {
        calls: usize,
    }

    impl PasteTrigger for FakeTrigger {
        fn post_paste(&mut self) -> Result<(), String> {
            self.calls += 1;
            Ok(())
        }
    }

    fn deps<'a>(sleeps: &'a mut Vec<f64>, token: &'a str) -> PasteDeps<'a> {
        PasteDeps {
            sleeper: Box::new(move |seconds| sleeps.push(seconds)),
            token: Box::new(move || token.to_string()),
        }
    }

    fn snapshot_with_text(text: &str) -> PasteboardSnapshot {
        PasteboardSnapshot {
            items: vec![vec![(
                "public.utf8-plain-text".to_string(),
                text.as_bytes().to_vec(),
            )]],
        }
    }

    #[test]
    fn the_full_flow_captures_places_pastes_and_restores() {
        let original = snapshot_with_text("原有剪贴板");
        let mut clipboard = FakeClipboard {
            snapshot: original.clone(),
            items: original.items.clone(),
            ..FakeClipboard::default()
        };
        let mut trigger = FakeTrigger::default();
        let mut sleeps = Vec::new();
        let mut deps = deps(&mut sleeps, "token-1");

        let outcome = paste_text_preserving_clipboard(
            &mut clipboard,
            &mut trigger,
            &mut deps,
            "听写结果",
            PasteWindow::default(),
        )
        .unwrap();

        assert_eq!(outcome, PasteOutcome::Restored);
        assert_eq!(trigger.calls, 1);
        drop(deps);
        assert_eq!(sleeps, [0.04, 0.25]);
        assert_eq!(clipboard.items, original.items);
        assert_eq!(
            clipboard.actions.first().map(String::as_str),
            Some("capture")
        );
        assert_eq!(
            clipboard.actions.last().map(String::as_str),
            Some("write_restored")
        );
    }

    #[test]
    fn user_copy_during_paste_is_never_overwritten() {
        let mut clipboard = FakeClipboard {
            snapshot: snapshot_with_text("旧内容"),
            ..FakeClipboard::default()
        };
        let mut trigger = FakeTrigger::default();
        let mut sleeps = Vec::new();
        let mut deps = deps(&mut sleeps, "token-1");
        // Simulate another app replacing the clipboard after ⌘V.
        trigger.calls = 0;

        let original_restore = clipboard.snapshot.clone();
        let outcome = paste_text_preserving_clipboard(
            &mut clipboard,
            &mut trigger,
            &mut deps,
            "听写结果",
            PasteWindow::default(),
        )
        .unwrap();
        assert_eq!(outcome, PasteOutcome::Restored);

        clipboard.token = Some("other-app".to_string());
        assert!(!should_restore(clipboard.token.as_deref(), "token-1"));
        assert_eq!(original_restore, snapshot_with_text("旧内容"));
    }

    #[test]
    fn restore_is_skipped_when_the_token_changed_mid_flow() {
        struct ChangingClipboard(FakeClipboard);
        impl ClipboardBackend for ChangingClipboard {
            fn capture(&mut self) -> PasteboardSnapshot {
                self.0.capture()
            }
            fn place_private_text(&mut self, text: &str, token: &str) -> Result<(), String> {
                let result = self.0.place_private_text(text, token);
                // Another app copies right after we place, but before restore.
                self.0.token = Some("other-app".to_string());
                result
            }
            fn current_token(&mut self) -> Option<String> {
                self.0.current_token()
            }
            fn clear(&mut self) {
                self.0.clear();
            }
            fn write_restored(&mut self, snapshot: &PasteboardSnapshot) -> Result<(), String> {
                self.0.write_restored(snapshot)
            }
        }

        let mut clipboard = ChangingClipboard(FakeClipboard {
            snapshot: snapshot_with_text("旧内容"),
            ..FakeClipboard::default()
        });
        let mut trigger = FakeTrigger::default();
        let mut sleeps = Vec::new();
        let mut deps = deps(&mut sleeps, "token-1");
        let outcome = paste_text_preserving_clipboard(
            &mut clipboard,
            &mut trigger,
            &mut deps,
            "听写结果",
            PasteWindow::default(),
        )
        .unwrap();
        assert_eq!(outcome, PasteOutcome::RestoreSkipped);
        assert!(!clipboard.0.actions.contains(&"clear".to_string()));
        assert!(!clipboard.0.actions.contains(&"write_restored".to_string()));
    }

    #[test]
    fn empty_text_does_not_touch_the_clipboard() {
        let mut clipboard = FakeClipboard::default();
        let mut trigger = FakeTrigger::default();
        let mut sleeps = Vec::new();
        let mut deps = deps(&mut sleeps, "token-1");
        let outcome = paste_text_preserving_clipboard(
            &mut clipboard,
            &mut trigger,
            &mut deps,
            "",
            PasteWindow::default(),
        )
        .unwrap();
        assert_eq!(outcome, PasteOutcome::EmptyText);
        assert!(clipboard.actions.is_empty());
        assert_eq!(trigger.calls, 0);
        drop(deps);
        assert!(sleeps.is_empty());
    }

    #[test]
    fn empty_snapshot_only_clears_and_still_reports_restored() {
        let mut clipboard = FakeClipboard::default();
        let mut trigger = FakeTrigger::default();
        let mut sleeps = Vec::new();
        let mut deps = deps(&mut sleeps, "token-1");
        let outcome = paste_text_preserving_clipboard(
            &mut clipboard,
            &mut trigger,
            &mut deps,
            "文字",
            PasteWindow::default(),
        )
        .unwrap();
        assert_eq!(outcome, PasteOutcome::Restored);
        assert!(clipboard.actions.contains(&"clear".to_string()));
        assert!(!clipboard.actions.contains(&"write_restored".to_string()));
        assert!(clipboard.items.is_empty());
    }

    #[test]
    fn restore_failure_does_not_report_a_broken_paste() {
        let mut clipboard = FakeClipboard {
            snapshot: snapshot_with_text("旧内容"),
            restore_error: true,
            ..FakeClipboard::default()
        };
        let mut trigger = FakeTrigger::default();
        let mut sleeps = Vec::new();
        let mut deps = deps(&mut sleeps, "token-1");
        let outcome = paste_text_preserving_clipboard(
            &mut clipboard,
            &mut trigger,
            &mut deps,
            "文字",
            PasteWindow::default(),
        )
        .unwrap();
        // The text reached the app; a restore failure is logged by the backend.
        assert_eq!(outcome, PasteOutcome::RestoreSkipped);
        assert_eq!(trigger.calls, 1);
    }

    #[test]
    fn wechat_gets_the_longer_settle_window() {
        assert_eq!(
            paste_window_for_bundle(Some("com.tencent.xinWeChat")),
            PasteWindow {
                before_paste_seconds: 0.04,
                settle_seconds: 0.85,
            }
        );
        assert_eq!(
            paste_window_for_bundle(Some("com.tencent.xwechat")),
            PasteWindow {
                before_paste_seconds: 0.04,
                settle_seconds: 0.85,
            }
        );
        assert_eq!(
            paste_window_for_bundle(Some("com.apple.TextEdit")),
            PasteWindow::default()
        );
        assert_eq!(paste_window_for_bundle(None), PasteWindow::default());
    }

    #[test]
    fn protocol_type_names_match_the_python_app() {
        assert_eq!(TOKEN_TYPE, "com.wjcdev.veyqa.private-paste-token");
        assert_eq!(SOURCE_BUNDLE_ID, "com.wjcdev.veyqa");
        assert_eq!(RESTORED_TYPE, "org.nspasteboard.RestoredType");
        assert_eq!(TRANSIENT_TYPE, "org.nspasteboard.TransientType");
    }
}
